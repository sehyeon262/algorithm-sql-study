n = int(input())
dp = [0] * 1005

dp[1] = 1
dp[2] = 2
dp[3] = 3

for i in range(4, n+1):
    # dp[i]를 만드는 두 가지 방법 (피보나치 수열과 동일한 원리)
    # 1) dp[i-1] 패턴에 세로 타일 1개(폭 1 차지)를 추가하는 경우
    # 2) dp[i-2] 패턴에 가로 타일 2개(폭 2 차지)를 위아래로 눕혀 추가하는 경우
    # 숫자가 기하급수적으로 커지는 것을 막기 위해 더할 때마다 10007로 나눈 나머지를 저장
    dp[i] = (dp[i - 1] + dp[i - 2]) % 10007

print(dp[n])
